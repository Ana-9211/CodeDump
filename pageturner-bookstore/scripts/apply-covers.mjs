// Attach cover images to the approved books, in shelf order.
//
//   node scripts/apply-covers.mjs <folder-of-images> [--dry-run]
//   npm run covers -- <folder-of-images> [--dry-run]
//
// The images are sorted by natural file name (cover2 before cover10) and matched, one to one, with the approved books
// in the order the shelf lists them (book_id ascending). If the number of images and approved books differ the script
// stops and changes nothing: it never guesses which image belongs to which book.
//
// For every pair it
//   1. copies the image to public/covers/<book_id>.<ext>
//   2. sets books.cover_url to /covers/<book_id>.<ext> in the database
//   3. writes db/postgres/11_covers.sql (keyed by ISBN) so `npm run db:reset` keeps the covers
// Books without a cover keep cover_url NULL and show the "cover pending" tile.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import pg from 'pg';
import { loadEnv } from '../src/lib/env.js';

loadEnv();
const EXT = new Set(['.jpg', '.jpeg', '.png', '.webp']);
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

function fail(message) {
  console.error(`\nERROR: ${message}\nNothing was changed.`);
  process.exit(1);
}

const args = process.argv.slice(2);
const dryRun = args.includes('--dry-run');
const folderArg = args.find((a) => !a.startsWith('--'));
if (!folderArg) fail('Usage: node scripts/apply-covers.mjs <folder-of-images> [--dry-run]');
const folder = path.resolve(folderArg);
if (!fs.existsSync(folder) || !fs.statSync(folder).isDirectory()) fail(`"${folder}" is not a folder.`);

const natural = new Intl.Collator('en', { numeric: true, sensitivity: 'base' });
const entries = fs.readdirSync(folder, { withFileTypes: true }).filter((e) => e.isFile());
const images = entries.filter((e) => EXT.has(path.extname(e.name).toLowerCase())).map((e) => e.name).sort(natural.compare);
const ignored = entries.filter((e) => !EXT.has(path.extname(e.name).toLowerCase())).map((e) => e.name);
if (ignored.length) console.log(`Ignoring ${ignored.length} file(s) that are not jpg, jpeg, png or webp: ${ignored.slice(0, 5).join(', ')}${ignored.length > 5 ? ', ...' : ''}`);

const adminUrl = new URL(process.env.DATABASE_ADMIN_URL || 'postgres://postgres@127.0.0.1:5432/postgres');
adminUrl.pathname = `/${process.env.DB_NAME || 'bookstore_dbms'}`;
const db = new pg.Client({ connectionString: adminUrl.toString() });
await db.connect().catch((e) => fail(`Cannot connect to the database: ${e.message}`));

const books = (await db.query("SELECT book_id, isbn, title FROM books WHERE status = 'approved' ORDER BY book_id")).rows;

if (images.length !== books.length) {
  console.error(`\nThe folder has ${images.length} image(s) but the shelf has ${books.length} approved book(s).`);
  console.error('First images, in the order they will be used:');
  images.slice(0, 5).forEach((f, i) => console.error(`  ${i + 1}. ${f}`));
  console.error('First books on the shelf:');
  books.slice(0, 5).forEach((b, i) => console.error(`  ${i + 1}. [${b.book_id}] ${b.title}`));
  await db.end();
  fail(`${images.length} images and ${books.length} books cannot be matched one to one.`);
}

const plan = books.map((b, i) => ({ ...b, file: images[i], ext: path.extname(images[i]).toLowerCase() === '.jpeg' ? '.jpeg' : path.extname(images[i]).toLowerCase() }));
console.log(`\n${dryRun ? 'DRY RUN - ' : ''}matching ${plan.length} images to ${plan.length} approved books:\n`);
for (const p of plan) console.log(`  ${String(p.book_id).padStart(3)}  ${p.title.padEnd(44).slice(0, 44)}  <-  ${p.file}`);

if (dryRun) {
  console.log('\nDry run only: no files copied, database and seed untouched.');
  await db.end();
  process.exit(0);
}

// 1. copy
const outDir = path.join(root, 'public', 'covers');
fs.mkdirSync(outDir, { recursive: true });
for (const p of plan) {
  for (const old of fs.readdirSync(outDir)) if (path.basename(old, path.extname(old)) === String(p.book_id)) fs.rmSync(path.join(outDir, old));
  fs.copyFileSync(path.join(folder, p.file), path.join(outDir, `${p.book_id}${p.ext}`));
}

// 2. database (one transaction)
await db.query('BEGIN');
try {
  for (const p of plan) await db.query('UPDATE books SET cover_url = $1 WHERE book_id = $2', [`/covers/${p.book_id}${p.ext}`, p.book_id]);
  await db.query('COMMIT');
} catch (e) {
  await db.query('ROLLBACK');
  await db.end();
  fail(`Database update failed: ${e.message}`);
}

// 3. seed file, so db:reset + db:seed keep the covers (keyed by ISBN, which is stable)
const lines = [
  '-- 11_covers.sql : generated by scripts/apply-covers.mjs. Do not edit by hand; run the script again instead.',
  '-- Sets the cover image of each approved book. The image files live in public/covers/.',
  ...plan.map((p) => `UPDATE books SET cover_url = '/covers/${p.book_id}${p.ext}' WHERE isbn = '${p.isbn}';`),
  '',
];
fs.writeFileSync(path.join(root, 'db', 'postgres', '11_covers.sql'), lines.join('\n'));
await db.end();
console.log(`\nDone: ${plan.length} covers copied to public/covers/, books.cover_url updated, db/postgres/11_covers.sql written.`);
console.log('Commit public/covers/ and db/postgres/11_covers.sql so db:reset keeps them.');
